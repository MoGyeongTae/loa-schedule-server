-- 관리자가 직접 생성하는 계정 테이블. 공개 회원가입 없음.
-- RLS만 켜 두고 공개 정책은 없음 (서버 service role만 접근).
-- user_role: 1=최고관리자, 2=일반관리자, 3=일반유저

create table public.users (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id text not null unique,
  password_hash text not null,
  display_name text not null,
  user_role smallint not null default 3,
  constraint users_user_id_length check (char_length(user_id) >= 3 and char_length(user_id) <= 30),
  constraint users_display_name_length check (char_length(display_name) >= 1 and char_length(display_name) <= 30),
  constraint users_user_role_check check (user_role in (1, 2, 3))
);

comment on table public.users is '관리자가 직접 생성하는 계정. 공개 가입 없음.';
comment on column public.users.user_role is '1=최고관리자, 2=일반관리자, 3=일반유저';

alter table public.users enable row level security;
